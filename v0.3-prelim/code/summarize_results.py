"""
summarize_results.py — D15-CORRECTED3 FIX-9: aggregated summary table
across all T-series fits.

Per review5.docx §4 short-term recommendation: "Add a single aggregated
summary table script to compile median/16-84% percentiles across all
T-series fits for direct manuscript insertion."

Reads all result JSONs in v0.3-prelim/data/results/, extracts the
key physical quantities, and writes:
  - outputs/summary_table.csv — for manuscript editing
  - outputs/summary_table.md — for README/changelog embedding
  - outputs/summary_table.txt — human-readable

The aggregator is intentionally conservative: it reads ONLY fields
that are unambiguously named (sigma_m_cm2_per_g_*, log_Z, MAP, etc.).
"""
from __future__ import annotations
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path("/home/lamkuenai/dm-sidm-pipeline/v0.3-prelim")
RESULTS_DIR = PROJECT_ROOT / "data" / "results"
OUTPUT_DIR = Path("/home/lamkuenai/dm-sidm-pipeline/outputs")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def safe_get(d, *keys, default=None):
    """Walk nested dict, return default if any key is missing."""
    for k in keys:
        if isinstance(d, dict) and k in d:
            d = d[k]
        else:
            return default
    return d


def collect_results():
    """Walk the results/ dir, return list of (name, summary_dict)."""
    summaries = []
    for path in sorted(RESULTS_DIR.glob("*.json")):
        try:
            d = json.load(open(path))
        except Exception:
            continue
        # Extract headline numbers
        s = {
            "name": path.stem,
            "test": d.get("test", path.stem),
            "direction": d.get("direction", "")[:60],
            "verdict": str(d.get("verdict", ""))[:80],
            "log_Z": safe_get(d, "log_Z"),
            "MAP_log_sigma_m": None,
            "median_log_sigma_m": None,
            "median_sigma_m": None,
            "sigma_m_16_84": None,
            "wall_seconds": d.get("wall_seconds"),
        }
        # Pull MAP / median from various locations
        # 1. flat MAP (2-list: [log_sigma_m, a])
        map_v = d.get("MAP")
        if isinstance(map_v, list) and len(map_v) >= 1 and isinstance(map_v[0], (int, float)):
            s["MAP_log_sigma_m"] = map_v[0]
        # 2. nested MAP (for T21-style fits)
        for fit_name, fit_data in d.items():
            if isinstance(fit_data, dict) and "MAP" in fit_data and isinstance(fit_data["MAP"], list):
                s["MAP_log_sigma_m"] = fit_data["MAP"][0]
                break
        # 3. median block (T39-style)
        med = d.get("median", {})
        if isinstance(med, dict):
            s["median_log_sigma_m"] = med.get("log_sigma_m_0")
            q = med.get("sigma_m_cm2_per_g_16_50_84")
            if isinstance(q, list) and len(q) == 3:
                s["median_sigma_m"] = q[1]
                s["sigma_m_16_84"] = f"{q[0]:.3f}-{q[2]:.3f}"
        summaries.append(s)
    return summaries


def write_csv(summaries):
    out = OUTPUT_DIR / "summary_table.csv"
    import csv
    with open(out, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "name", "direction", "log_Z", "MAP_log_sigma_m",
            "median_log_sigma_m", "median_sigma_m_cm2_per_g",
            "sigma_m_16_84_cm2_per_g", "wall_seconds", "verdict_short",
        ])
        for s in summaries:
            writer.writerow([
                s["name"], s["direction"],
                s["log_Z"] if s["log_Z"] is not None else "",
                s["MAP_log_sigma_m"] if s["MAP_log_sigma_m"] is not None else "",
                s["median_log_sigma_m"] if s["median_log_sigma_m"] is not None else "",
                s["median_sigma_m"] if s["median_sigma_m"] is not None else "",
                s["sigma_m_16_84"] if s["sigma_m_16_84"] is not None else "",
                s["wall_seconds"] if s["wall_seconds"] is not None else "",
                s["verdict"][:60],
            ])
    return out


def write_md(summaries):
    out = OUTPUT_DIR / "summary_table.md"
    lines = ["# dm-sidm-pipeline T-series summary", ""]
    lines.append("**Generated by `summarize_results.py` (D15-CORRECTED3 FIX-9).**")
    lines.append("")
    lines.append("All results as of " + str(Path(__file__).name) + ". See `data/results/*.json` for full JSON.")
    lines.append("")
    lines.append("| name | direction | log Z | MAP log σ/m | median log σ/m | median σ/m (cm²/g) | σ/m 16-84% (cm²/g) | wall (s) | verdict |")
    lines.append("|------|-----------|-------|-------------|----------------|---------------------|----------------------|----------|---------|")
    for s in summaries:
        lines.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            s["name"],
            s["direction"][:50],
            f"{s['log_Z']:.3f}" if s["log_Z"] is not None else "—",
            f"{s['MAP_log_sigma_m']:.3f}" if s["MAP_log_sigma_m"] is not None else "—",
            f"{s['median_log_sigma_m']:.3f}" if s["median_log_sigma_m"] is not None else "—",
            f"{s['median_sigma_m']:.3f}" if s["median_sigma_m"] is not None else "—",
            s["sigma_m_16_84"] or "—",
            f"{s['wall_seconds']:.1f}" if s["wall_seconds"] is not None else "—",
            s["verdict"][:60],
        ))
    out.write_text("\n".join(lines))
    return out


def write_txt(summaries):
    out = OUTPUT_DIR / "summary_table.txt"
    lines = []
    for s in summaries:
        lines.append(f"=== {s['name']} ===")
        lines.append(f"  direction: {s['direction']}")
        lines.append(f"  log_Z: {s['log_Z']}")
        lines.append(f"  MAP_log_sigma_m: {s['MAP_log_sigma_m']}")
        lines.append(f"  median_log_sigma_m: {s['median_log_sigma_m']}")
        lines.append(f"  median_sigma_m: {s['median_sigma_m']}")
        lines.append(f"  sigma_m_16_84: {s['sigma_m_16_84']}")
        lines.append(f"  wall_seconds: {s['wall_seconds']}")
        lines.append(f"  verdict: {s['verdict']}")
        lines.append("")
    out.write_text("\n".join(lines))
    return out


def main():
    print("summarize_results.py — aggregating T-series results")
    summaries = collect_results()
    print(f"Found {len(summaries)} result JSONs")
    csv_out = write_csv(summaries)
    md_out = write_md(summaries)
    txt_out = write_txt(summaries)
    print(f"  CSV -> {csv_out}")
    print(f"  MD  -> {md_out}")
    print(f"  TXT -> {txt_out}")
    print()
    print("Headline:")
    for s in summaries[:10]:
        if s["log_Z"] is not None:
            print(f"  {s['name']}: log_Z = {s['log_Z']:.3f}")


if __name__ == "__main__":
    main()